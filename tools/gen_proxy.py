"""Generates the wsock32.dll forwarding stubs (src/proxy_stubs.asm, src/wsock32.def,
src/proxy_exports.h) from the exports of C:\\Windows\\System32\\wsock32.dll.
Ordinal-only exports are forwarded by ordinal; DllMain is not exported.
"""
import pathlib
import pefile

root = pathlib.Path(__file__).resolve().parent.parent
pe = pefile.PE(r"C:\Windows\System32\wsock32.dll")
exports = []
for e in pe.DIRECTORY_ENTRY_EXPORT.symbols:
    name = e.name.decode() if e.name else None
    if name == "DllMain":
        continue
    exports.append((e.ordinal, name))
exports.sort()

def stub(ordinal, name):
    return f"{name}_proxy" if name else f"Ord{ordinal}_proxy"

asm = ["; generated by tools/gen_proxy.py - do not edit", "EXTERN g_proxyTargets:QWORD", ".code"]
for i, (ordinal, name) in enumerate(exports):
    s = stub(ordinal, name)
    asm += [f"{s} PROC", f"    jmp QWORD PTR [g_proxyTargets + {i * 8}]", f"{s} ENDP"]
asm.append("END")
(root / "src" / "proxy_stubs.asm").write_text("\n".join(asm) + "\n")

defs = ["; generated by tools/gen_proxy.py - do not edit", "LIBRARY wsock32", "EXPORTS"]
for ordinal, name in exports:
    if name:
        defs.append(f"    {name}={stub(ordinal, name)} @{ordinal}")
    else:
        defs.append(f"    {stub(ordinal, name)} @{ordinal} NONAME")
(root / "src" / "wsock32.def").write_text("\n".join(defs) + "\n")

header = ["// generated by tools/gen_proxy.py - do not edit", "#pragma once", "#include <cstdint>",
          f"constexpr int kProxyExportCount = {len(exports)};",
          "// name, or nullptr for an export that only has an ordinal",
          "static const char* const kProxyExportNames[kProxyExportCount] = {"]
header += [f'    "{name}",' if name else "    nullptr," for _, name in exports]
header.append("};")
header.append("static const uint16_t kProxyExportOrdinals[kProxyExportCount] = {")
header += [f"    {ordinal}," for ordinal, _ in exports]
header.append("};")
(root / "src" / "proxy_exports.h").write_text("\n".join(header) + "\n")
print(f"generated {len(exports)} forwarders")
